  const dict = { zh, en };

  function detect() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved === 'zh' || saved === 'en') return saved;
    } catch {}
    const nav = (navigator.languages && navigator.languages[0]) || navigator.language || 'zh';
    return /^zh/i.test(nav) ? 'zh' : 'en';
  }

  let lang = detect();
  applyDocumentLang();

  function applyDocumentLang() {
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  }

  function t(key, vars) {
    let s = dict[lang][key];
    if (s == null) s = zh[key];
    if (s == null) return key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? vars[k] : ''));
    return s;
  }

  function setLang(next) {
    if (next !== 'zh' && next !== 'en' || next === lang) return;
    lang = next;
    try { localStorage.setItem(STORAGE_KEY, next); } catch {}
    applyDocumentLang();
    listeners.forEach((fn) => { try { fn(lang); } catch (e) { console.error(e); } });
  }

  function onChange(fn) { listeners.push(fn); }

  const locale = () => (lang === 'zh' ? 'zh-CN' : 'en-US');

  function num(n) { return Number(n || 0).toLocaleString(locale()); }

  function date(value, withTime = true) {
    const d = value instanceof Date ? value : new Date(value);
    if (Number.isNaN(d.getTime())) return '';
    const opts = { year: 'numeric', month: 'short', day: 'numeric' };
    if (withTime) Object.assign(opts, { hour: '2-digit', minute: '2-digit', hour12: false });
    return d.toLocaleString(locale(), opts);
  }

  function time(value) {
    return new Date(value).toLocaleTimeString(locale(), { hour: '2-digit', minute: '2-digit', second: '2-digit', hour12: false });
  }

  // Maps API error strings (see internal/handler) to readable, localized copy.
  function error(err) {
    const raw = String((err && (err.apiError || err.message)) || '').toLowerCase();
    const status = err && err.status;
    if (err && err.network) return t('err.network');
    if (raw.includes('invalid email or password')) return t('err.badLogin');
    if (raw.includes('验证码') || raw.includes('captcha')) return t('err.captcha');
    if (raw.includes('email already registered')) return t('err.emailTaken');
    if (raw.includes('insufficient balance') || status === 402) return t('err.insufficient');
    if (raw.includes('journey not found')) return t('err.journeyNotFound');
    if (raw.includes('order not found')) return t('err.orderNotFound');
    if (raw.includes('mbti')) return t('err.mbti');
    if (raw.includes('512kb')) return t('err.avatarSize');
    if (raw.includes('jpeg, png, or webp')) return t('err.avatarType');
    if (raw.includes('username')) return t('err.username');
    if (raw.includes('password must')) return t('err.password');
    if (raw.includes("'email'")) return t('err.email');
    if (status === 401) return t('err.session');
    if (status === 403) return t('err.forbidden');
    if (status === 429) return t('err.rateLimit');
    if (status >= 500) return t('err.server');
    if (status === 400) return t('err.invalid');
    return t('err.server');
  }

  return {
    t, setLang, onChange, num, date, time, error,
    get lang() { return lang; },
    get apiLang() { return lang; },
  };
